// Zen's settings page tags each row's control with the setting's name in
// its tooltip; Sine's gives the row the setting's name as its id (dots as
// dashes), inside each mod's settings dialog.
function rowFor(name) {
  const tagged = document.querySelector(`[tooltiptext="${CSS.escape(name)}"]`);
  const zenRow = tagged?.closest(".zenThemeMarketplaceItemPreference");
  if (zenRow) return zenRow;
  const sineRow = document.getElementById(name.replaceAll(".", "-"));
  return sineRow?.closest(".sineItemPreferenceDialogContent") ? sineRow : null;
}

function apply() {
  for (const [name, rule] of Object.entries(RULES)) {
    const row = rowFor(name);
    if (!row) continue;
    let reason = null;
    try {
      // A setting for another platform, or one whose conditions don't hold.
      const elsewhere = rule.platform && rule.platform !== Services.appinfo.OS;
      reason = elsewhere || !holds(rule.conditions) ? rule.why : null;
    } catch (e) {
      console.error(`[Zenith] settings rule for ${name}`, e);
    }
    row.toggleAttribute("zenith-off", !!reason);
    const control = row.querySelector("checkbox, menulist, input");
    if (control) control.disabled = !!reason;
    let note = row.querySelector(":scope > .zenith-why");
    if (reason) {
      if (!note) {
        note = document.createXULElement("label");
        note.className = "zenith-why";
        row.append(note);
      }
      note.setAttribute("value", reason);
    } else {
      note?.remove();
    }
  }
}

function init() {
  const style = document.createElementNS(HTML_NS, "style");
  style.textContent = STYLE;
  (document.head ?? document.documentElement).append(style);

  let pending = false;
  const schedule = () => {
    if (pending) return;
    pending = true;
    window.requestAnimationFrame(() => {
      pending = false;
      apply();
      arrangeSinePage();
      noteAutoUpdate();
    });
  };
  // Zen builds the mod list (and rebuilds it) after the page loads.
  const mo = new MutationObserver(schedule);
  mo.observe(document.documentElement, { childList: true, subtree: true });
  Services.prefs.addObserver("zenith.", schedule);
  Services.prefs.addObserver("sine.auto-updates", schedule);
  window.addEventListener("unload", () => {
    mo.disconnect();
    Services.prefs.removeObserver("zenith.", schedule);
    Services.prefs.removeObserver("sine.auto-updates", schedule);
  }, { once: true });
  schedule();
}

// Once per page, even with two copies of Zenith installed for a moment.
if (!window.zenithSettingsStarted) {
  window.zenithSettingsStarted = true;
  try {
    init();
  } catch (e) {
    console.error("[Zenith] settings helper failed to start", e);
  }
}
