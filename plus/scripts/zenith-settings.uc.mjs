// Sine's own condition logic (unset dropdowns read as "", tick boxes as false).
function test(cond) {
  const c = cond.if || cond.not;
  let value;
  if (typeof c.value === "boolean") value = Services.prefs.getBoolPref(c.property, false);
  else if (typeof c.value === "number") value = Services.prefs.getIntPref(c.property, 0);
  else value = Services.prefs.getStringPref(c.property, "");
  return cond.not ? value !== c.value : value === c.value;
}

function holds(conds, operator = "AND") {
  const results = conds.map(c => (c.if || c.not ? test(c) : holds(c.conditions, c.operator || "AND")));
  return operator === "OR" ? results.some(Boolean) : results.every(Boolean);
}

// --- Sine's mods page: your mods first, the marketplace folded -------------
// Sine puts its marketplace (#sineInstallationGroup: search, a grid of
// store mods, install-from-GitHub) above your installed mods
// (#sineInstalledGroup). With "your mods first" on, the installed list moves
// up and the store grid folds behind a button; searching unfolds it.
function arrangeSinePage() {
  if (!Services.prefs.getBoolPref("zenith.plus.sine-mods-first", true)) return;
  const store = document.getElementById("sineInstallationGroup");
  const mine = document.getElementById("sineInstalledGroup");
  if (!store || !mine || store.hasAttribute("zenith-arranged")) return;
  store.setAttribute("zenith-arranged", "true");
  store.before(mine);
  store.setAttribute("zenith-folded", "true");
  const header = store.querySelector("#sineMarketplaceHeader") ?? store.firstElementChild;
  const toggle = document.createXULElement("button");
  toggle.className = "zenith-browse";
  const label = () => toggle.setAttribute("label",
    store.hasAttribute("zenith-folded") ? "Browse the marketplace" : "Hide the marketplace");
  label();
  toggle.addEventListener("command", () => {
    store.toggleAttribute("zenith-folded");
    label();
  });
  header?.append(toggle);
  store.querySelector("#sineInstallationHeader input")?.addEventListener("input", () => {
    store.removeAttribute("zenith-folded");
    label();
  });
}

// Sine's "Auto-Update" button is a switch, not "update now", and its state
// shows only as a colour; switched off, mods (Zenith too) stop updating when
// Zen starts. A note next to it says so while it's off.
function noteAutoUpdate() {
  const box = document.querySelector("#sineInstalledGroup .updates-container");
  if (!box) return;
  const off = !Services.prefs.getBoolPref("sine.auto-updates", true);
  let note = box.querySelector(".zenith-update-note");
  if (off && !note) {
    note = document.createXULElement("label");
    note.className = "zenith-update-note";
    note.setAttribute("value", "Auto-update is off: mods only update when you press Update");
    box.append(note);
  } else if (!off) {
    note?.remove();
  }
}

