function addCategory() {
  const categories = document.getElementById("categories");
  const general = categories?.querySelector("#category-general");
  if (!categories || !general || document.getElementById("category-zenith")) return false;
  const after = document.getElementById("category-sine-mods") ?? general;
  let item;
  if (general.localName === "moz-page-nav-button") {
    item = document.createElementNS(HTML_NS, "moz-page-nav-button");
    item.setAttribute("view", PANE);
    item.setAttribute("iconsrc", ICON);
    item.textContent = "Zenith";
  } else {
    item = document.createXULElement("richlistitem");
    item.className = "category";
    item.setAttribute("value", PANE);
    item.setAttribute("tooltiptext", "Zenith");
    item.setAttribute("align", "center");
    const image = document.createXULElement("image");
    image.className = "category-icon";
    image.style.listStyleImage = `url("${ICON}")`;
    const label = document.createXULElement("label");
    label.className = "category-name";
    label.setAttribute("flex", "1");
    label.setAttribute("value", "Zenith");
    item.append(image, label);
  }
  item.id = "category-zenith";
  after.after(item);
  gCategoryInits.set(PANE, { _initted: true, init() {} });
  return true;
}

