const Find = {
  // Every setting on this platform (and each section's preset), with where
  // it lives and the words it can be found by.
  entries() {
    if (this.all) return this.all;
    this.all = [];
    for (const section of SCHEMA) {
      if (section.preset) {
        const options = section.preset.values.map(v => ({ label: v.label, value: v.value }));
        this.all.push({ kind: "preset", section, label: `${section.title} preset`, place: section.title, options,
                        words: `${section.title} preset ${options.map(o => o.label).join(" ")}`.toLowerCase() });
      }
      for (const group of section.groups) {
        for (const s of group.settings) {
          if ((s.rule?.platform && s.rule.platform !== OS) || s.type === "string") continue;
          if (s.type === "action") {
            this.all.push({ kind: "action", s, section, label: s.label, place: `${section.title} › ${group.title}`,
                            options: [{ label: s.button, value: "" }],
                            words: `${s.label} ${section.title} ${group.title} ${s.desc} ${s.button}`.toLowerCase() });
            continue;
          }
          const options = s.type === "checkbox" ? [{ label: "On", value: true }, { label: "Off", value: false }] : s.options;
          this.all.push({ kind: "setting", s, section, label: s.label, place: `${section.title} › ${group.title}`, options,
                          words: `${s.label} ${section.title} ${group.title} ${s.desc} ${options.map(o => o.label).join(" ")}`.toLowerCase() });
        }
      }
    }
    return this.all;
  },

  current(e) {
    if (e.kind === "action") return "";
    return e.kind === "preset" ? presetOf(e.section) : effective(e.s, e.section);
  },

  // What it's set to, as the page shows it.
  value(e) {
    const v = this.current(e);
    const label = e.options.find(o => o.value === v)?.label ?? String(v);
    return e.kind === "preset" && isCustom(e.section) ? `${label} (changed)` : label;
  },

  // Why it does nothing right now, if it doesn't (the page greys it out).
  why(e) {
    if (e.kind !== "setting" || !e.s.rule?.conditions) return null;
    try {
      return holds(e.s.rule.conditions) ? null : e.s.rule.why;
    } catch {
      return null;
    }
  },

  // Settings matching every word, the closest names first.
  find(query) {
    const q = query.trim().toLowerCase();
    const words = q.split(/\s+/).filter(Boolean);
    if (!words.length) return [];
    const rank = e => {
      const name = e.label.toLowerCase();
      if (name === q) return 0;
      if (name.startsWith(q)) return 1;
      if (words.every(w => name.includes(w))) return 2;
      if (words.every(w => `${name} ${e.place.toLowerCase()}`.includes(w))) return 3;
      return 4;
    };
    return this.entries().filter(e => words.every(w => e.words.includes(w)))
      .map((e, i) => [rank(e), i, e]).sort((a, b) => a[0] - b[0] || a[1] - b[1]).map(x => x[2]);
  },

  // The next (dir 1) or previous (-1) choice, written at once.
  step(e, dir) {
    if (e.kind === "action") return runAction(e.s);
    const values = e.options.map(o => o.value);
    const i = values.indexOf(this.current(e));
    const next = values[(i + dir + values.length) % values.length];
    if (e.kind === "preset") choosePreset(e.section, next);
    else write(e.s, next);
  },

  open(e) {
    if (e.kind === "action") return runAction(e.s);
    Live.open(e);
  },
};

function startPanel() {
  // A command and key of our own (no inline handler, which the window's
  // policy blocks); "reserved" keeps pages from taking Alt+Shift+Z.
  const commandset = document.createXULElement("commandset");
  const command = document.createXULElement("command");
  command.id = "zenith-live-command";
  command.addEventListener("command", () => Live.toggle());
  commandset.append(command);
  const keyset = document.createXULElement("keyset");
  keyset.id = "zenith-live-keys";
  const key = document.createXULElement("key");
  key.id = "zenith-live-key";
  key.setAttribute("modifiers", "alt,shift");
  key.setAttribute("key", "Z");
  key.setAttribute("reserved", "true");
  key.setAttribute("command", "zenith-live-command");
  keyset.append(key);
  document.documentElement.append(commandset, keyset);
  window.ZenithLive = Live; // for tools/checks
  window.ZenithSettings = Find; // Peek's "set"
  return true;
}

// Zen's Keyboard shortcuts list Zenith's keys (zenith-plus.uc.mjs adds them
// to Zen's list) with no name of their own: they get "Zenith: …" here,
// whenever Zen draws the list.
function labelZenithKeys() {
  const names = new Map((window.browsingContext?.topChromeWindow?.ZenithKeys?.LIST ?? []).map(k => [k[0], `Zenith: ${k[4]}`]));
  if (!names.size) return;
  const label = () => {
    for (const input of document.querySelectorAll("input.zenCKSOption-input[data-id^='zenith-key-']")) {
      const text = names.get(input.dataset.id);
      const node = input.closest(".zenCKSOption")?.querySelector(".zenCKSOption-label");
      if (!text || !node || node.textContent === text) continue;
      node.removeAttribute("data-l10n-id");
      node.textContent = text;
    }
  };
  new MutationObserver(label).observe(document, { childList: true, subtree: true });
  label();
}

// Once per window or page. In Zen's Settings, Sine adds its own category a
// moment after load, so wait for the list to settle before joining it.
if (!window.zenithSettingsPageStarted) {
  window.zenithSettingsPageStarted = true;
  const inBrowser = location.href.startsWith("chrome://browser/content/browser.xhtml");
  if (!inBrowser) labelZenithKeys();
  let tries = 0;
  const attempt = () => {
    try {
      if (inBrowser ? startPanel() : startPage()) return;
    } catch (e) {
      console.error("[Zenith] settings failed to start", e);
      return;
    }
    if (++tries < 40) setTimeout(attempt, 150);
  };
  attempt();
}
