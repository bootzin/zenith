/* --- Reading and writing settings --------------------------------------------- */

const P = Services.prefs;

function stored(s) {
  if (s.type === "checkbox") {
    if (P.getPrefType(s.property) === P.PREF_BOOL) return P.getBoolPref(s.property);
    return s.default ?? false;
  }
  return P.getStringPref(s.property, "");
}

function presetOf(section) {
  return P.getStringPref(section.preset.property, "") || section.preset.default;
}

// What a setting is actually doing: its own value, else what the section's
// preset gives it, else its default.
function effective(s, section) {
  const own = stored(s);
  if (s.type !== "dropdown" || own) return own;
  const byPreset = section.preset?.sets[s.property];
  if (byPreset) return byPreset[presetOf(section)];
  return s.default ?? "";
}

// A button that opens something of Zen's (Space routing): run its command
// in the browser window, wherever the page is.
function runAction(s) {
  const win = window.gBrowser ? window : Services.wm.getMostRecentWindow("navigator:browser");
  // With Fast start, the part behind the button may still be waiting its
  // turn: start everything now.
  if (!win?.document.getElementById(s.command)) win?.zenithLater?.now();
  win?.document.getElementById(s.command)?.doCommand();
}

function write(s, value) {
  if (s.type === "checkbox") P.setBoolPref(s.property, value);
  else if (value === "" || value == null) P.clearUserPref(s.property);
  else P.setStringPref(s.property, value);
}

// Choosing a preset writes it into every setting it covers.
function choosePreset(section, value) {
  P.setStringPref(section.preset.property, value);
  for (const [prop, byPreset] of Object.entries(section.preset.sets)) P.setStringPref(prop, byPreset[value]);
}

function isCustom(section) {
  const preset = presetOf(section);
  return Object.entries(section.preset.sets).some(([prop, byPreset]) => {
    const own = P.getStringPref(prop, "");
    return own && own !== byPreset[preset];
  });
}

// Sine's condition format (the same rules the settings helper uses).
function test(cond) {
  const c = cond.if || cond.not;
  let value;
  if (typeof c.value === "boolean") value = P.getBoolPref(c.property, false);
  else value = P.getStringPref(c.property, "");
  return cond.not ? value !== c.value : value === c.value;
}

function holds(conds, operator = "AND") {
  const results = conds.map(c => (c.if || c.not ? test(c) : holds(c.conditions, c.operator || "AND")));
  return operator === "OR" ? results.some(Boolean) : results.every(Boolean);
}

