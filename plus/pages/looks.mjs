// Zenith's settings as everything that shows or changes them reads and
// writes them: the rice picker, the bars and their menus, the settings page,
// themes. The one place that knows
//   - what a setting is: its value when that's one of its choices, else its
//     default (a blank or unknown value is the default, never "nothing");
//   - each bar's own values: zenith.bar.<edge>.<key>, else the bars' shared
//     zenith.bar.<key>;
//   - what choosing a bar's look, Theme › Corners or Theme › Window
//     transparency writes into the bars: concrete values, so every setting
//     always shows one.
// The rule (docs/reference.md §11): code that shows a setting reads it here,
// and code that changes a look writes it here, never with its own fallback.
// The schema is generated by tools/build_prefs.py.

import { SCHEMA, PRESETS } from "./schema.mjs";

const P = Services.prefs;

export { SCHEMA };
export const EDGES = ["top", "bottom", "left", "right"];
// What each bar can have its own of.
export const BAR_KEYS = ["style", "size", "length", "font", "icons", "margin", "corners", "opacity", "module-corners", "spacing",
                         "border", "separators"];
// What a look decides (written when one is chosen).
export const SHAPE_KEYS = ["margin", "corners", "opacity", "module-corners", "spacing", "separators"];
// Window transparency's steps, as a bar's background.
export const TRANSPARENCY = { solid: "100", dense: "92", balanced: "82", airy: "66", sheer: "46", glass: "28" };
// Theme › Corners, as a floating bar's corners and the modules'.
const CORNERS = { square: { bar: "0", modules: "0" }, soft: { bar: "12", modules: "8" }, round: { bar: "18", modules: "999" } };
// The looks that join their modules edge to edge: these don't apply to them.
const JOINED = { strip: ["module-corners", "spacing"], minimal: ["module-corners", "spacing"], powerline: ["module-corners", "spacing", "separators"] };
// The bar fonts before 0.18.2 (Monospace, the browser's): now a font's name.
const OLD_FONTS = /^(mono\w*|system)$/;
// What a theme holds: looks only (never layout, keys or behaviour).
export const THEME_KEYS = [
  "zenith.palette", "zenith.core.accent", "zenith.core.corners", "zenith.core.density", "zenith.core.glass", "zenith.core.glass-edge",
  "zenith.core.window-transparency", "zenith.core.font", "zenith.core.pills", ...BAR_KEYS.map(k => `zenith.bar.${k}`),
];

function raw(p) {
  const t = P.getPrefType(p);
  if (t === P.PREF_BOOL) return P.getBoolPref(p);
  if (t === P.PREF_INT) return String(P.getIntPref(p));
  if (t === P.PREF_STRING) return P.getStringPref(p);
  return null;
}

export function entry(p) {
  return SCHEMA[p] ?? null;
}

// One of the setting's choices (any text for a text setting, any whole
// number on a size's slider).
export function valid(p, v) {
  if (v === null || v === undefined || v === "") return false;
  const options = SCHEMA[p]?.options;
  return !options || options.some(o => o.value === v) || inRange(SCHEMA[p].range, v);
}

// A size's slider (schema "range": min, max in pixels, and an end past
// them, "Fully round"): a value on it.
export function inRange(range, v) {
  return !!range && (v === range.end?.value || (/^\d+$/.test(v) && +v >= range.min && +v <= range.max));
}

// A slider's stops: a size's every pixel (and its end), else its choices in
// order. min, max; at(value) its stop; value(stop); text(stop).
export function stops(options, range) {
  const said = v => options.find(o => o.value === v)?.label?.replace(/ \(.*\)$/, "");
  if (!range) {
    return { min: 0, max: options.length - 1, at: v => Math.max(0, options.findIndex(o => o.value === v)), value: i => options[i].value, text: i => said(options[i].value) };
  }
  const top = range.max + (range.end ? 1 : 0), value = i => (range.end && i === top ? range.end.value : String(i));
  return {
    min: range.min, max: top,
    at: v => (v === range.end?.value ? top : Math.min(range.max, Math.max(range.min, parseInt(v, 10) || 0))),
    value,
    text: i => said(value(i)) ?? `${i}px`,
  };
}

function presetValue(preset) {
  const info = PRESETS[preset], v = raw(preset);
  return info.values.includes(v) ? v : info.default;
}

// What the setting is when nothing (valid) is set: its section preset's
// value for it, else its own default.
export function defaultOf(p) {
  for (const [preset, info] of Object.entries(PRESETS)) {
    const by = info.sets[p];
    if (by) return by[presetValue(preset)] ?? by[info.default];
  }
  return SCHEMA[p]?.default ?? "";
}

export function value(p) {
  const v = raw(p);
  if (SCHEMA[p]?.type === "checkbox") return typeof v === "boolean" ? v : !!SCHEMA[p].default;
  if (PRESETS[p]) return presetValue(p);
  return valid(p, v) ? v : defaultOf(p);
}

// A value as the settings say it ("Airy (66%)").
export function label(p, v = value(p)) {
  const e = SCHEMA[p];
  if (e?.type === "checkbox") return v ? "On" : "Off";
  return e?.options?.find(o => o.value === v)?.label ?? (e?.range && /^\d+$/.test(v) ? `${v}px` : v || "None");
}

// The default written as itself too: it then shows as chosen.
export function set(p, v) {
  if (typeof v === "boolean") P.setBoolPref(p, v);
  else P.setStringPref(p, String(v));
}

export function changed(p) {
  return P.prefHasUserValue(p) && valid(p, raw(p)) && value(p) !== defaultOf(p);
}

export const Bars = {
  pref(edge, key) {
    return `zenith.bar.${edge}.${key}`;
  },

  // This bar's own value (one set for it alone), else the bars' shared one.
  value(edge, key) {
    return this.own(edge, key) ? raw(this.pref(edge, key)) : value(`zenith.bar.${key}`);
  },

  own(edge, key) {
    return valid(`zenith.bar.${key}`, raw(this.pref(edge, key)));
  },

  // "all": every bar (the shared value, and no bar keeps its own); or one bar.
  set(scope, key, v) {
    if (scope !== "all") return set(this.pref(scope, key), v);
    set(`zenith.bar.${key}`, v);
    for (const e of EDGES) P.clearUserPref(this.pref(e, key));
  },

  // The bars (other than the shared value) that have their own: [edge, value].
  others(key) {
    return EDGES.filter(e => this.own(e, key) && raw(this.pref(e, key)) !== value(`zenith.bar.${key}`)).map(e => [e, raw(this.pref(e, key))]);
  },

  looks() {
    return SCHEMA["zenith.bar.style"].options.map(o => o.value);
  },

  // How a look is drawn with Theme › Corners and Window transparency.
  shape(look, corners = value("zenith.core.corners"), glass = value("zenith.core.window-transparency")) {
    const c = CORNERS[corners] ?? CORNERS.soft, pills = ["islands", "floating", "bare"].includes(look);
    return {
      margin: look === "floating" || look === "bare" ? "8" : "0",
      corners: look === "floating" ? c.bar : "0",
      opacity: look === "bare" ? "0" : TRANSPARENCY[glass] ?? TRANSPARENCY.airy,
      "module-corners": pills ? c.modules : "0",
      spacing: pills ? "6" : "0",
      separators: look === "minimal" ? "line" : "off",
    };
  },

  // A look for one bar or all of them, with the shape it's drawn in.
  chooseLook(scope, look) {
    this.set(scope, "style", look);
    for (const [k, v] of Object.entries(this.shape(look))) this.set(scope, k, v);
  },

  // Theme › Corners or Window transparency chosen: these keys of every bar
  // follow (each bar with a look of its own, in that look).
  reshape(keys) {
    const shared = this.shape(value("zenith.bar.style"));
    for (const k of keys) set(`zenith.bar.${k}`, shared[k]);
    for (const e of EDGES) {
      const mine = this.own(e, "style") ? this.shape(raw(this.pref(e, "style"))) : null;
      for (const k of keys) mine ? set(this.pref(e, k), mine[k]) : P.clearUserPref(this.pref(e, k));
    }
  },

  // What a bar's setting is when it hasn't been changed: what its look
  // writes (the shape), else the setting's default.
  base(scope, key) {
    const look = scope === "all" ? value("zenith.bar.style") : this.value(scope, "style");
    return SHAPE_KEYS.includes(key) ? this.shape(look)[key] : defaultOf(`zenith.bar.${key}`);
  },

  // Why a setting doesn't apply to a look; else null.
  fixed(look, key) {
    if (!JOINED[look]?.includes(key)) return null;
    return `${label("zenith.bar.style", look).replace(/ \(.*\)$/, "")} joins its modules edge to edge`;
  },
};

// Changing a look setting: Theme › Corners and Window transparency also
// write the bars' corners and background, a bar's look its shape.
export function setLook(p, v) {
  if (p === "zenith.bar.style") return Bars.chooseLook("all", v);
  set(p, v);
  if (p === "zenith.core.corners") {
    set("zenith.core.pills", v === "square" ? "match" : "round");
    Bars.reshape(["corners", "module-corners"]);
  }
  if (p === "zenith.core.window-transparency") Bars.reshape(["opacity"]);
}

// A section's preset (Motion's, say): it and every setting it covers.
export function choosePreset(preset, v) {
  set(preset, v);
  for (const [p, by] of Object.entries(PRESETS[preset].sets)) if (by[v] !== undefined) set(p, by[v]);
}

export { PRESETS };

// Every look setting a theme or the picker can change, as it's stored
// (null: not set), to put back exactly.
export function snapshot(extra = []) {
  const names = [...THEME_KEYS, ...EDGES.flatMap(e => BAR_KEYS.map(k => Bars.pref(e, k))), ...extra];
  return Object.fromEntries(names.map(p => [p, P.prefHasUserValue(p) ? raw(p) : null]));
}

export function restore(saved) {
  for (const [p, v] of Object.entries(saved)) {
    if (v === null) P.clearUserPref(p);
    else set(p, v);
  }
}

// A theme: what it names, every other look setting at its default, and the
// bars drawn in the theme's look (its own bar values win).
export function applyTheme(sets) {
  restore(Object.fromEntries(Object.keys(snapshot()).map(p => [p, null])));
  for (const [p, v] of Object.entries(sets)) {
    if (SHAPE_KEYS.some(k => p === `zenith.bar.${k}`) || v === null || v === "" || (/\.font$/.test(p) && OLD_FONTS.test(v))) continue;
    set(p, v);
  }
  const shape = Bars.shape(value("zenith.bar.style"));
  for (const k of SHAPE_KEYS) set(`zenith.bar.${k}`, valid(`zenith.bar.${k}`, sets[`zenith.bar.${k}`]) ? sets[`zenith.bar.${k}`] : shape[k]);
}

// Settings from before 0.18.1, once: "as its look has it" became the look's
// own values, the side bars' width two settings, the bar's old background
// steps the transparency ones; a value that isn't one of a setting's
// choices (a typo in the rice file) goes back to the default.
export function migrate() {
  const look = value("zenith.bar.style"), shape = Bars.shape(look);
  for (const k of SHAPE_KEYS) {
    const p = `zenith.bar.${k}`;
    if (raw(p) === "auto" || !P.prefHasUserValue(p) || raw(p) === "") set(p, shape[k]);
  }
  const old = { 90: "92", 75: "82", 50: "46", 25: "28" }[raw("zenith.bar.opacity")];
  if (old) set("zenith.bar.opacity", old);
  const side = parseInt(raw("zenith.bar.side-px") ?? "", 10);
  if (!isNaN(side)) set(side < 120 ? "zenith.bar.rail-px" : "zenith.bar.wide-px", String(side));
  if (P.prefHasUserValue("zenith.bar.side-px")) P.clearUserPref("zenith.bar.side-px");
  if (raw("zenith.motion.space-switch") === "preset") P.clearUserPref("zenith.motion.space-switch");
  // (0.16.0's dot and short line: the ring and the top line.)
  const hint = { dot: "ring", line: "top" }[raw("zenith.bar.container-hint")];
  if (hint) set("zenith.bar.container-hint", hint);
  // (0.18.1's bar fonts, Monospace and the browser's: the browser's font,
  // or one you pick by name.)
  for (const p of [`zenith.bar.font`, ...EDGES.map(e => Bars.pref(e, "font"))]) if (OLD_FONTS.test(raw(p) ?? "")) P.clearUserPref(p);
  // (0.18.1's Glance buttons beside the page as Zen has them, or on the
  // other side: the side that is.)
  const glance = raw("zenith.plus.glance-buttons"), right = P.getBoolPref("zen.tabs.vertical.right-side", false);
  if (glance === "zen" || glance === "other-side") set("zenith.plus.glance-buttons", (glance === "zen") !== right ? "right" : "left");
  for (const [p, e] of Object.entries(SCHEMA)) {
    if (e.type !== "dropdown" || !p.startsWith("zenith.") || !P.prefHasUserValue(p)) continue;
    const v = raw(p), n = String(parseInt(v, 10));
    if (v === "" || valid(p, v)) continue;
    // ("28 24 20" for a size: its first number, when that's a choice.)
    if (valid(p, n)) set(p, n);
    else P.clearUserPref(p);
    console.warn(`[Zenith] ${p}: ${JSON.stringify(v)} isn't one of its choices, so it's now ${JSON.stringify(value(p))}`);
  }
}
